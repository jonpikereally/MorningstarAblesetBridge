#!/bin/zsh
# Build a release: Apple silicon app (no Intel slice since v2.8) with an installer,
# written to updates/MorningstarAblesetBridge.zip + updates/latest.json. Committing and
# pushing updates/ ships it: every installed copy's "Check for Updates" reads
# latest.json from this repo on GitHub.
#
#   bump VERSION, write RELEASE_NOTES.txt (or set UPDATE_NOTES), then ./release.sh
set -e
cd "$(dirname "$0")"
VERSION=$(cat VERSION)
# Every error code used in the app and installer must be on the public error list.
missing=$(grep -ohE 'MAB-[0-9]{3}' Sources/MorningstarAblesetBridge/*.swift release.sh install.sh | sort -u | while read -r c; do
  grep -q "^| $c |" ERRORS.md || echo "$c"
done)
if [[ -n "$missing" ]]; then
  echo "Error codes missing from ERRORS.md: $missing" >&2
  exit 1
fi
if [[ -z "${UPDATE_NOTES:-}" && -f RELEASE_NOTES.txt ]]; then
  UPDATE_NOTES=$(<RELEASE_NOTES.txt)
fi
BUILT=$(date "+%b %d, %H:%M")
FEED="${UPDATE_FEED-https://raw.githubusercontent.com/jonpikereally/MorningstarAblesetBridge/main/updates/latest.json}"
cat > Sources/MorningstarAblesetBridge/Version.swift <<SWIFT
// Generated by build.sh / release.sh — do not edit.
enum AppVersion {
    static let version = "$VERSION"
    static let built = "$BUILT"
    static let updateFeed = "$FEED"
}
SWIFT
CACHE="${TMPDIR:-/tmp}/mab-modcache"
mkdir -p "$CACHE"
echo "Building arm64…"
swiftc -O -target arm64-apple-macos13 -module-cache-path "$CACHE" \
  -o "$CACHE/MorningstarAblesetBridge-arm64" Sources/MorningstarAblesetBridge/*.swift

DIST="$CACHE/dist"
rm -rf "$DIST"
APP="$DIST/MorningstarAblesetBridge/MorningstarAblesetBridge.app"
mkdir -p "$APP/Contents/MacOS"
cp "$CACHE/MorningstarAblesetBridge-arm64" "$APP/Contents/MacOS/MorningstarAblesetBridge"
cp Resources/Info.plist "$APP/Contents/Info.plist"
mkdir -p "$APP/Contents/Resources"
cp Resources/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist"
codesign --force --sign - "$APP"

cat > "$DIST/MorningstarAblesetBridge/Install MorningstarAblesetBridge.command" <<'INSTALL'
#!/bin/bash
# MorningstarAblesetBridge installer — copies the app to ~/Applications and launches it.
cd "$(dirname "$0")"
fail() {
  echo
  echo "Error $1: $2"
  echo "Look up this code on the MorningstarAblesetBridge error list:"
  echo "  https://github.com/jonpikereally/MorningstarAblesetBridge/blob/main/ERRORS.md"
  echo "(You can also give that page to an AI assistant for help.)"
  exit 1
}
echo "Installing MorningstarAblesetBridge…"
mkdir -p ~/Applications || fail MAB-601 "Couldn't create ~/Applications."
rm -rf ~/Applications/MorningstarAblesetBridge.app
ditto --norsrc MorningstarAblesetBridge.app ~/Applications/MorningstarAblesetBridge.app \
  || fail MAB-601 "Couldn't copy MorningstarAblesetBridge into ~/Applications."
# Clear the download quarantine and re-sign locally so macOS trusts it on this Mac.
xattr -dr com.apple.quarantine ~/Applications/MorningstarAblesetBridge.app 2>/dev/null
codesign --force --sign - ~/Applications/MorningstarAblesetBridge.app 2>/dev/null \
  || fail MAB-602 "Couldn't sign MorningstarAblesetBridge for this Mac."
open ~/Applications/MorningstarAblesetBridge.app \
  || fail MAB-603 "MorningstarAblesetBridge was installed but couldn't be opened. Open it from ~/Applications yourself."
echo
echo "Done! Look for \"MC4\" in your menu bar (see README.txt to set up the pedal)."
INSTALL
chmod +x "$DIST/MorningstarAblesetBridge/Install MorningstarAblesetBridge.command"

cat > "$DIST/MorningstarAblesetBridge/README.txt" <<README
MorningstarAblesetBridge v$VERSION — AbleSet song names and play/loop state on a
Morningstar MC4 PRO footswitch (Apple silicon Mac, macOS 13+)
https://github.com/jonpikereally/MorningstarAblesetBridge

INSTALL
1. Double-click "Install MorningstarAblesetBridge.command".
   If macOS blocks it: right-click it, choose Open, then Open again.
2. Look for "MC4" in the menu bar.

SET UP
1. Load the AbleSet Bridge bank (bank/AbleSet Bridge.json in the GitHub repo)
   into a bank slot with the Morningstar editor.
2. Connect the MC4 PRO to this Mac over Bluetooth MIDI or USB.
3. In AbleSet, map notes 12 (play), 13 (stop), 14 (loop), 15 (previous song)
   and 16 (next song), plus 20/21 (previous/next section), on channel 1. Don't map CC 111 or CC 112.
4. In Ableton Live's MIDI settings, turn on Remote for the pedal's input.

The pedal controls AbleSet by itself; the app only changes what it shows.

PRIVACY
The app talks only to AbleSet on your own Mac (UDP, 127.0.0.1) and to the
pedal over MIDI. No accounts, no analytics. The only thing it fetches from
the internet is a small version file from the GitHub repo above, to see
whether an update exists.
README

mkdir -p updates
(cd "$DIST" && ditto -c -k --norsrc --noextattr --noqtn --keepParent MorningstarAblesetBridge "$OLDPWD/updates/MorningstarAblesetBridge.zip.tmp")
mv -f updates/MorningstarAblesetBridge.zip.tmp updates/MorningstarAblesetBridge.zip
# The feed points at a copy named for this version: raw.githubusercontent.com
# caches each file for ~5 minutes, so a fixed name could hand the updater the
# previous zip right after a release (v1.6: "installs, then offers the update
# again"). The plain-named zip stays for the README's download link.
find updates -name "MorningstarAblesetBridge-*.zip" -delete
cp updates/MorningstarAblesetBridge.zip "updates/MorningstarAblesetBridge-$VERSION.zip"
# Manifest last, so a checking app never sees it pointing at a half-written zip.
/usr/bin/python3 -c 'import json,sys; print(json.dumps({"version": sys.argv[1], "url": "MorningstarAblesetBridge-" + sys.argv[1] + ".zip", "notes": sys.argv[2]}))' \
  "$VERSION" "${UPDATE_NOTES:-}" > updates/latest.json.tmp
mv -f updates/latest.json.tmp updates/latest.json

./build.sh >/dev/null
echo "Release v$VERSION written to updates/. Ship it with:"
echo "  git add -A && git commit -m \"Release v$VERSION\" && git push"
